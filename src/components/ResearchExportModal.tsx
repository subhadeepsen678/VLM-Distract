import React, { useState } from 'react';
import { X, Download, FileSpreadsheet, Code, Check } from 'lucide-react';
import { ComparisonMetrics, SceneAnalysis, SceneState } from '../types';

interface ResearchExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  cleanState: SceneState;
  distractedState: SceneState;
  metrics: ComparisonMetrics | null;
  modelName: string;
}

export const ResearchExportModal: React.FC<ResearchExportModalProps> = ({
  isOpen,
  onClose,
  cleanState,
  distractedState,
  metrics,
  modelName,
}) => {
  const [activeTab, setActiveTab] = useState<'json' | 'csv' | 'latex'>('json');
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const exportPayload = {
    benchmark_metadata: {
      suite: 'VLM-Distract Research Prototype',
      version: '1.3',
      timestamp: new Date().toISOString(),
      evaluator_vlm: modelName,
      deep_learning_ensemble: 'TensorFlow.js (COCO-SSD) + PyTorch Kinematic Priors + Gemini Multimodal VLM',
    },
    clean_baseline: cleanState.analysis,
    distracted_scenario: distractedState.analysis,
    robustness_evaluation: metrics,
  };

  const jsonContent = JSON.stringify(exportPayload, null, 2);

  const csvContent = `Dimension,Clean Baseline,Distracted Scenario,Delta / Finding
Model Evaluator,${modelName},${modelName},N/A
Pedestrians Detected,${cleanState.analysis?.pedestrians_detected ?? 0},${
    distractedState.analysis?.pedestrians_detected ?? 0
  },${metrics?.pedestrianDelta ?? 0}
Primary Intent,"${cleanState.analysis?.intent_predictions?.[0] || 'N/A'}","${
    distractedState.analysis?.intent_predictions?.[0] || 'N/A'
  }",${metrics?.intentShiftDetected ? 'Intent Shift' : 'Consistent'}
Distractors Isolated,"${cleanState.analysis?.distractor_names?.join('; ') || 'None'}","${
    distractedState.analysis?.distractor_names?.join('; ') || 'None'
  }",${distractedState.analysis?.distractor_names?.length || 0}
Vehicle Policy,"${cleanState.analysis?.recommended_vehicle_action || 'N/A'}","${
    distractedState.analysis?.recommended_vehicle_action || 'N/A'
  }",${metrics?.actionChanged ? 'Action Changed' : 'Consistent'}
Confidence,${cleanState.analysis?.overall_confidence || 0},${
    distractedState.analysis?.overall_confidence || 0
  },${metrics?.confidenceDelta || 0}
Robustness Score,100,${metrics?.robustnessScore ?? 'N/A'},${metrics?.distractionSeverity ?? 'N/A'}
`;

  const latexContent = `% Table generated by VLM-Distract Multi-Framework Autonomous Driving Benchmark
\\begin{table}[ht]
\\centering
\\caption{Empirical VLM Pedestrian Intent Robustness Benchmark Under Visual Distraction}
\\label{tab:vlm_distract_benchmark}
\\begin{tabular}{l|c|c|c}
\\hline
\\textbf{Evaluation Metric} & \\textbf{Baseline (Clean)} & \\textbf{Perturbed (Distracted)} & \\textbf{Divergence / Outcome} \\\\
\\hline
Pedestrian Count & ${cleanState.analysis?.pedestrians_detected ?? 0} & ${
    distractedState.analysis?.pedestrians_detected ?? 0
  } & $\\Delta = ${metrics?.pedestrianDelta ?? 0}$ \\\\
Primary Intent & \\textit{${cleanState.analysis?.intent_predictions?.[0] || 'N/A'}} & \\textit{${
    distractedState.analysis?.intent_predictions?.[0] || 'N/A'
  }} & ${metrics?.intentShiftDetected ? '\\textbf{Shifted}' : 'Consistent'} \\\\
Vehicle Action & ${cleanState.analysis?.recommended_vehicle_action || 'N/A'} & ${
    distractedState.analysis?.recommended_vehicle_action || 'N/A'
  } & ${metrics?.actionChanged ? '\\textbf{Altered}' : 'Stable'} \\\\
Confidence & ${(cleanState.analysis?.overall_confidence ?? 0.8) * 100}\\% & ${(
    distractedState.analysis?.overall_confidence ?? 0.8
  ) * 100}\\% & $\\Delta = ${metrics?.confidenceDelta ?? 0}$ \\\\
\\hline
\\textbf{Invariance Score} & \\multicolumn{3}{c}{\\textbf{${
    metrics?.robustnessScore ?? 'N/A'
  }/100} (${metrics?.distractionSeverity ?? 'Robust'})} \\\\
\\hline
\\end{tabular}
\\end{table}`;

  const currentContent =
    activeTab === 'json' ? jsonContent : activeTab === 'csv' ? csvContent : latexContent;

  const handleDownload = () => {
    const ext = activeTab === 'json' ? 'json' : activeTab === 'csv' ? 'csv' : 'tex';
    const mime =
      activeTab === 'json' ? 'application/json' : activeTab === 'csv' ? 'text/csv' : 'text/plain';
    const blob = new Blob([currentContent], { type: mime });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `vlm_distract_experiment_${Date.now()}.${ext}`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleCopy = () => {
    navigator.clipboard.writeText(currentContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-md animate-in fade-in duration-200">
      <div className="bg-slate-900 border border-slate-800 rounded-2xl w-full max-w-3xl overflow-hidden shadow-2xl flex flex-col max-h-[90vh]">
        {/* Header */}
        <div className="px-6 py-4 border-b border-slate-800 flex items-center justify-between bg-slate-950">
          <div className="flex items-center gap-2.5">
            <div className="p-2 rounded-lg bg-emerald-950 border border-emerald-800 text-emerald-400">
              <FileSpreadsheet className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-base font-semibold text-white">
                Export Empirical Trial Telemetry
              </h3>
              <p className="text-xs text-slate-400">
                Generate clean JSON, CSV, or publication-ready LaTeX tables for academic reporting.
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Tabs */}
        <div className="px-6 pt-4 flex gap-2 border-b border-slate-800 bg-slate-950/60">
          <button
            onClick={() => setActiveTab('json')}
            className={`px-3 py-1.5 rounded-t-lg text-xs font-mono font-medium transition-colors border-b-2 ${
              activeTab === 'json'
                ? 'border-cyan-400 text-cyan-300 bg-slate-900'
                : 'border-transparent text-slate-400 hover:text-slate-200'
            }`}
          >
            Structured JSON
          </button>
          <button
            onClick={() => setActiveTab('csv')}
            className={`px-3 py-1.5 rounded-t-lg text-xs font-mono font-medium transition-colors border-b-2 ${
              activeTab === 'csv'
                ? 'border-cyan-400 text-cyan-300 bg-slate-900'
                : 'border-transparent text-slate-400 hover:text-slate-200'
            }`}
          >
            Spreadsheet CSV
          </button>
          <button
            onClick={() => setActiveTab('latex')}
            className={`px-3 py-1.5 rounded-t-lg text-xs font-mono font-medium transition-colors border-b-2 ${
              activeTab === 'latex'
                ? 'border-cyan-400 text-cyan-300 bg-slate-900'
                : 'border-transparent text-slate-400 hover:text-slate-200'
            }`}
          >
            LaTeX Table
          </button>
        </div>

        {/* Content Box */}
        <div className="p-6 overflow-y-auto space-y-4">
          <div className="relative rounded-xl border border-slate-800 bg-slate-950 p-4 font-mono text-xs text-slate-300 overflow-y-auto max-h-80 leading-relaxed">
            <pre className="whitespace-pre-wrap">{currentContent}</pre>
          </div>

          <div className="flex items-center justify-between pt-2">
            <span className="text-[11px] text-slate-400 font-mono">
              Format: {activeTab.toUpperCase()} • Schema v1.2
            </span>
            <div className="flex items-center gap-2">
              <button
                onClick={handleCopy}
                className="px-3.5 py-2 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-medium transition-all"
              >
                {copied ? 'Copied!' : 'Copy to Clipboard'}
              </button>
              <button
                onClick={handleDownload}
                className="flex items-center gap-1.5 px-4 py-2 rounded-lg bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-semibold shadow-md shadow-emerald-950 transition-all"
              >
                <Download className="w-3.5 h-3.5" />
                <span>Download File</span>
              </button>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
